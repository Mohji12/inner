# Ensure every supported platform language has a catalog entry.
assert SUPPORTED_LANGS <= set(_LABELS.keys()), "invoice PDF catalogs missing a supported language"


def invoice_lang(raw: str | None) -> str:
    """Normalize to a catalog language; unknown → default."""
    lang = normalize_lang(raw)
    return lang if lang in _LABELS else DEFAULT_LANG


def invoice_labels(lang: str | None) -> dict[str, str]:
    return _LABELS[invoice_lang(lang)]


def t_invoice(lang: str | None, key: str, **kwargs: object) -> str:
    labels = invoice_labels(lang)
    template = labels.get(key) or _LABELS[DEFAULT_LANG].get(key) or key
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, ValueError):
            return template
    return template


def localize_payment_status(status: str | None, lang: str | None) -> str:
    raw = (status or "").strip()
    if not raw:
        return ""
    if raw.lower() == "paid":
        return t_invoice(lang, "paid")
    return raw


def booking_line_description(
    *,
    lang: str | None,
    duration_minutes: int,
    mentor_name: str,
    session_topic: str | None = None,
) -> str:
    line = t_invoice(
        lang,
        "line_mentorship",
        minutes=duration_minutes,
        mentor_name=mentor_name,
    )
    topic = (session_topic or "").strip()
    if topic:
        return f"{line} — {topic}"
    return line


def format_invoice_duration(seconds: int, lang: str | None) -> str:
    h = seconds // 3600
    m = (seconds % 3600) // 60
    s = seconds % 60
    if h:
        return t_invoice(lang, "duration_hms", h=h, m=m, s=s)
    if m:
        return t_invoice(lang, "duration_ms", m=m, s=s)
    return t_invoice(lang, "duration_s", s=s)
